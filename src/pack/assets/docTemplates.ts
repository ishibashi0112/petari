/**
 * プロジェクト文書(docs/)のひな型の正本。
 *
 * 3 種類の文書を slnmix が既定のひな型として内蔵する(フェーズ 6、設計書 §18)。
 *
 * - design  設計書: 開発の進め方と判断の根拠。確認事項がゼロになるまで
 *           AI と質疑応答で仕上げ、必須の確認事項がなくなったら実装に進む
 * - spec    仕様書: 実装済みの振る舞いの正本。誰が読んでも分かる書き方を求める
 * - handoff 引継ぎ書: チャット間の状態のみ(1 ファイル固定、毎回書き直す)
 *
 * ひな型は本文用テキスト(.prompt.md)の <template> として AI に渡す。
 * 文書を新しく作るとき AI はこの章立てに従う。ルート直下の
 * docs/templates/<kind>.md があればその内容で置き換える(procedure.md と同じ扱い)。
 *
 * Mermaid(flowchart / stateDiagram / erDiagram)を章立てに組み込み、md ビューアで
 * 処理の流れが図として読めるようにしている。HTML コメントは AI 向けの記入指示で、
 * 完成した文書には残さない(ひな型の末尾に明記)。
 *
 * 文面を変えたら DOC_TEMPLATES_VERSION を上げ、tests/fixtures/pack/docs/ の
 * スナップショットを更新すること。
 */

